#!/usr/bin/env python3
# gen_tables.py FFREF_DIR OUT.c: pull the Indeo 4/5 format constants (numbers only) out of
# FFmpeg's table sources and write them as openindeo's tables.c under our own names.
import re
import sys

ref, out = sys.argv[1], sys.argv[2]
src = {f: open(f"{ref}/{f}", encoding="latin-1").read() for f in ("ivi.c", "indeo4data.h", "indeo5data.h")}


def body(name):
    for text in src.values():
        m = re.search(r"\b" + re.escape(name) + r"\s*(\[[^=]*\])?\s*=\s*\{", text)
        if not m:
            continue
        i, depth = m.end() - 1, 0
        for j in range(i, len(text)):
            if text[j] == "{":
                depth += 1
            elif text[j] == "}":
                depth -= 1
                if depth == 0:
                    return text[i:j + 1]
    raise SystemExit(f"no table {name}")


def numbers(name):
    b = re.sub(r"/\*.*?\*/", "", body(name), flags=re.S)
    b = re.sub(r"//[^\n]*", "", b)
    return [int(v, 0) for v in re.findall(r"-?(?:0x[0-9a-fA-F]+|\d+)", b)]


def emit(f, ctype, name, vals, per_row=16, dims=""):
    f.write(f"const {ctype} {name}{dims} = {{\n")
    inner = re.findall(r"\[(\d+)\]", dims)
    groups = [vals] if len(inner) < 2 else [vals[k:k + int(inner[1])] for k in range(0, len(vals), int(inner[1]))]
    for g in groups:
        pad = "    " if len(groups) == 1 else "        "
        if len(groups) > 1:
            f.write("    {\n")
        for k in range(0, len(g), per_row):
            f.write(pad + ", ".join(str(v) for v in g[k:k + per_row]) + ",\n")
        if len(groups) > 1:
            f.write("    },\n")
    f.write("};\n\n")


with open(out, "w") as f:
    f.write("""/* Indeo 4/5 format constants: Huffman codebook layouts, run/value maps, scan orders,
 * dequantisation tables and picture sizes. These are fixed by the bitstream format.
 *
 * Generated by tools/gen_tables.py. Provisional source: FFmpeg's published tables (numbers
 * only). The source of record is to be Intel's own codec (ir41_32 / ir50_32); the two are to
 * be diffed once its tables are extracted.
 */
#include "tables.h"

""")
    # Huffman descriptors: {rows, xbits[rows]} each.
    for which in ("mb", "blk"):
        vals = numbers(f"ivi_{which}_huff_desc")
        rows = []
        k = 0
        while k < len(vals):
            n = vals[k]
            rows.append((n, vals[k + 1:k + 1 + n]))
            k += 1 + n
        assert len(rows) == 8, which
        f.write(f"const oi_huff_desc oi_{which}_huff_desc[8] = {{\n")
        for n, xb in rows:
            f.write(f"    {{{n}, {{{', '.join(map(str, xb))}}}}},\n")
        f.write("};\n\n")
    # Run/value maps: 9 x {eob, esc, run[256], val[256]}.
    vals = numbers("ff_ivi_rvmap_tabs")
    assert len(vals) == 9 * 514, len(vals)
    f.write("const oi_rvmap oi_rvmap_tabs[9] = {\n")
    for t in range(9):
        v = vals[t * 514:(t + 1) * 514]
        f.write(f"  {{ /* map {t} */\n    {v[0]}, {v[1]},\n    {{\n")
        for k in range(0, 256, 16):
            f.write("      " + ", ".join(str(x) for x in v[2 + k:2 + k + 16]) + ",\n")
        f.write("    },\n    {\n")
        for k in range(0, 256, 16):
            f.write("      " + ", ".join(str(x) for x in v[258 + k:258 + k + 16]) + ",\n")
        f.write("    }\n  },\n")
    f.write("};\n\n")
    scans = [("ff_ivi_vertical_scan_8x8", "oi_vertical_scan_8x8", 64),
             ("ff_ivi_horizontal_scan_8x8", "oi_horizontal_scan_8x8", 64),
             ("ff_ivi_direct_scan_4x4", "oi_direct_scan_4x4", 16),
             ("ivi4_alternate_scan_8x8", "oi_alternate_scan_8x8", 64),
             ("ivi4_alternate_scan_4x4", "oi_alternate_scan_4x4", 16),
             ("ivi4_vertical_scan_4x4", "oi_vertical_scan_4x4", 16),
             ("ivi4_horizontal_scan_4x4", "oi_horizontal_scan_4x4", 16)]
    for theirs, ours, n in scans:
        v = numbers(theirs)
        assert len(v) == n, theirs
        emit(f, "uint8_t", ours, v, 8 if n == 64 else 4, f"[{n}]")
    tabs = [("ivi5_common_pic_sizes", "oi_ivi5_pic_sizes", "uint8_t", 30, ""),
            ("ivi5_base_quant_8x8_inter", "oi_ivi5_base_quant_8x8_inter", "uint16_t", 5 * 64, "[5][64]"),
            ("ivi5_base_quant_8x8_intra", "oi_ivi5_base_quant_8x8_intra", "uint16_t", 5 * 64, "[5][64]"),
            ("ivi5_base_quant_4x4_inter", "oi_ivi5_base_quant_4x4_inter", "uint16_t", 16, ""),
            ("ivi5_base_quant_4x4_intra", "oi_ivi5_base_quant_4x4_intra", "uint16_t", 16, ""),
            ("ivi5_scale_quant_8x8_inter", "oi_ivi5_scale_quant_8x8_inter", "uint8_t", 5 * 24, "[5][24]"),
            ("ivi5_scale_quant_8x8_intra", "oi_ivi5_scale_quant_8x8_intra", "uint8_t", 5 * 24, "[5][24]"),
            ("ivi5_scale_quant_4x4_inter", "oi_ivi5_scale_quant_4x4_inter", "uint8_t", 24, ""),
            ("ivi5_scale_quant_4x4_intra", "oi_ivi5_scale_quant_4x4_intra", "uint8_t", 24, ""),
            ("ivi4_common_pic_sizes", "oi_ivi4_pic_sizes", "uint16_t", 14, ""),
            ("ivi4_quant_8x8_intra", "oi_ivi4_quant_8x8_intra", "uint16_t", 9 * 64, "[9][64]"),
            ("ivi4_quant_8x8_inter", "oi_ivi4_quant_8x8_inter", "uint16_t", 9 * 64, "[9][64]"),
            ("ivi4_quant_4x4_intra", "oi_ivi4_quant_4x4_intra", "uint16_t", 5 * 16, "[5][16]"),
            ("ivi4_quant_4x4_inter", "oi_ivi4_quant_4x4_inter", "uint16_t", 5 * 16, "[5][16]"),
            ("quant_index_to_tab", "oi_ivi4_quant_index_to_tab", "uint8_t", 22, "")]
    for theirs, ours, ctype, n, dims in tabs:
        v = numbers(theirs)
        assert len(v) == n, (theirs, len(v))
        emit(f, ctype, ours, v, 16, dims or f"[{n}]")
print("wrote", out)
